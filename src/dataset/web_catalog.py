def timing(lots: pd.DataFrame) -> dict:
    recent = lots[(lots["requestTimeBegin"] >= TIMING_FROM) & (lots["requestTimeBegin"] < TIMING_TO) & lots["first_date"].notna()]
    days = (sold_at(recent) - recent["first_date"]).dt.days
    at_first = (recent["first_date"] == recent["requestTimeBegin"]) & (recent["stage"] == "аукцион")
    return {name: {f"p{int(q * 100)}": int(days[mask].quantile(q)) for q in (0.25, 0.5, 0.75)}
            for name, mask in [("first_auction", at_first), ("later", ~at_first)]}


def main() -> None:
    lots = read_lots(LOTS_PATH).dropna(subset=["make", "model"])
    counts = lots.groupby(["make", "model"]).size()
    counts = counts[counts >= MIN_LOTS]
    makes = {make: sorted(group.index.get_level_values("model"), key=str.lower)
             for make, group in counts.groupby(level="make")}
    catalog = {
        "makes": dict(sorted(makes.items(), key=lambda kv: kv[0].lower())),
        "regions": [{"id": str(code), "name": name} for code, name in sorted(REGIONS.items(), key=lambda kv: kv[1])],
        "timing_days": timing(lots),
    }
    OUT_PATH.write_text(json.dumps(catalog, ensure_ascii=False, indent=1))
    print(f"{len(makes)} makes, {len(counts)} models, {len(REGIONS)} regions, timing {catalog['timing_days']} -> {OUT_PATH}")


if __name__ == "__main__":
    main()
